# ================= monthly shapes (bridged so each year compounds to the exact annual return) =========
import math
def bridge(points, annual):
    """points: 13 positive levels (prior Dec .. this Dec). returns 12 cumulative multipliers ending at 1+annual%"""
    base=points[0]; lg=[math.log(p/base) for p in points]; target=math.log(1+annual/100); gap=target-lg[12]
    return [round(math.exp(lg[k]+gap*k/12),5) for k in range(1,13)]
